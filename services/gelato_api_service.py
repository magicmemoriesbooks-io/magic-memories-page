def _get_draft_price(
    country_code: str,
    shipment_uid: str,
    currency: str = "USD",
    postal_code: str = None,
) -> Optional[float]:
    """
    Create a Gelato draft order and extract the total cost (print + shipping).
    Uses the customer's postal_code if provided for accuracy.
    Cancels the draft immediately after getting the price.
    Returns total cost in USD, or None on failure.
    """
    ref_id = f"QUOTE-{uuid.uuid4().hex[:10]}"
    addr_template = _FALLBACK_ADDRESS_BY_COUNTRY.get(country_code, {
        "country": country_code, "city": "Test City",
        "postCode": "00000", "state": "", "addressLine1": "1 Test St",
    })
    effective_postcode = postal_code or addr_template["postCode"]

    payload = {
        "orderType": "draft",
        "orderReferenceId": ref_id,
        "customerReferenceId": ref_id,
        "currency": currency,
        "items": [{
            "itemReferenceId": f"{ref_id}-1",
            "productUid": HC_A4_SKU,
            "quantity": 1,
            "pageCount": 30,
            "fileUrl": _PLACEHOLDER_PDF,
        }],
        "shipmentMethodUid": shipment_uid,
        "shippingAddress": {
            "firstName": "Quote",
            "lastName": "Request",
            "addressLine1": addr_template["addressLine1"],
            "city": addr_template["city"],
            "postCode": effective_postcode,
            "state": addr_template.get("state", ""),
            "country": addr_template["country"],
            "email": "quote@magicmemoriesbooks.com",
            "phone": "+10000000000",
        },
    }

    try:
        resp = requests.post(
            f"{GELATO_API_BASE}/v3/orders",
            headers=_headers(), json=payload, timeout=25,
        )
        if resp.status_code not in (200, 201):
            print(f"[GELATO QUOTE] Draft failed for {country_code}/{shipment_uid}: {resp.status_code} — {resp.text[:300]}")
            return None

        data = resp.json()
        order_id = data.get("id")
        # Debug log: show raw pricing fields so we can verify what Gelato returns
        print(f"[GELATO QUOTE DEBUG] {country_code}/{shipment_uid} raw keys: {list(data.keys())}")
        print(f"[GELATO QUOTE DEBUG] totalCost={data.get('totalCost')} price={data.get('price')} total={data.get('total')} billing={data.get('billing')}")
        items_raw = data.get("items", [])
        for _i in items_raw:
            print(f"[GELATO QUOTE DEBUG] item price={_i.get('price')} cost={_i.get('cost')} quantity={_i.get('quantity')}")
        total = _extract_total_from_order(data)

        if order_id:
            try:
                requests.delete(f"{GELATO_API_BASE}/v3/orders/{order_id}", headers=_headers(), timeout=10)
                print(f"[GELATO QUOTE] Draft {order_id} cancelled after pricing")
            except Exception:
                pass

        if total and total > 0:
            print(f"[GELATO QUOTE] {country_code}/{shipment_uid}: ${total:.2f}")
            return round(total, 2)

    except Exception as e:
        print(f"[GELATO QUOTE] Exception for {country_code}/{shipment_uid}: {e}")

    return None


def _extract_total_from_order(data: dict) -> Optional[float]:
    """
    Extract the total cost (print + shipping) from a Gelato v3 order response.

    Primary: sums 'price' from receipts[].items grouped by type:
      - type=product   → print cost
      - type=shipment  → shipping cost
      - type=packaging → packaging cost
    Fallback: reads item.price from the items array (print only, shipping=0).
    """
    # ── Primary: receipts breakdown ────────────────────────────────────────
    receipts = data.get("receipts") or []
    if receipts:
        print_cost = 0.0
        ship_cost = 0.0
        packaging_cost = 0.0
        found = False
        for receipt in receipts:
            for ri in receipt.get("items", []):
                try:
                    price = float(ri.get("price") or 0)
                except (TypeError, ValueError):
                    price = 0.0
                rtype = (ri.get("type") or "").lower()
                if rtype == "product":
                    print_cost += price
                    found = True
                elif rtype == "shipment":
                    ship_cost += price
                    found = True
                elif rtype == "packaging":
                    packaging_cost += price
        if found:
            total = print_cost + ship_cost + packaging_cost
            print(f"[GELATO QUOTE DEBUG] receipts → print={print_cost:.2f} ship={ship_cost:.2f} pkg={packaging_cost:.2f} total={total:.2f}")
            return round(total, 2)

    # ── Fallback: item.price (print cost only, no shipping) ────────────────
    items = data.get("items", [])
    item_cost = 0.0
    found_item = False
    for item in items:
        for field in ("price", "totalPrice", "cost"):
            val = item.get(field)
            if val is not None:
                try:
                    item_cost += float(val)
                    found_item = True
                    break
                except (TypeError, ValueError):
                    pass
    if found_item:
        print(f"[GELATO QUOTE DEBUG] fallback item.price → {item_cost:.2f} (shipping not captured)")
        return round(item_cost, 2)

    return None


def get_shipping_quote(
    country_code: str,
    currency: str = "USD",
    postal_code: str = None,
) -> dict:
    """
    Get real-time Gelato shipping options and costs for a given country.

    First attempts to use the Gelato /v3/shipment-methods endpoint.
    If that endpoint does not return pricing, falls back to creating
    draft orders (one per method) to get actual total costs (print + shipping).
    The customer's postal_code is used in draft orders when provided for accuracy.
    Draft orders are cancelled immediately after getting the price.

    Returns a dict keyed by shipmentMethodUid:
    {
        'express': {
            'name_es': str,
            'name_en': str,
            'days_es': str,
            'days_en': str,
            'gelato_cost': float,   # Gelato total charged (print + shipping)
        },
        ...
    }
    Returns empty dict if the country is not supported or the API fails.
    """
    # ── Step 1: /v3/shipment-methods — method availability + delivery days ONLY ──
    # IMPORTANT: the `price` field from this endpoint is shipping-only and does NOT
    # include the print cost. We never use it as gelato_cost. We only extract method
    # UIDs and delivery-day ranges here, then always fetch real totals via draft orders.
    try:
        resp = requests.get(
            f"{GELATO_API_BASE}/v3/shipment-methods",
            headers=_headers(),
            params={"country": country_code, "currency": currency, "productUid": HC_A4_SKU},
            timeout=15,
        )
        if resp.status_code == 200:
            raw_methods = resp.json().get("shipmentMethods", [])
            if raw_methods:
                method_uids = [
                    m.get("shipmentMethodUid") or m.get("uid")
                    for m in raw_methods
                    if m.get("shipmentMethodUid") or m.get("uid")
                ]
                method_uids = [u for u in method_uids if u][:3]  # limit to 3
                days_by_uid = {
                    (m.get("shipmentMethodUid") or m.get("uid")): (
                        m.get("minDeliveryDays", ""), m.get("maxDeliveryDays", "")
                    )
                    for m in raw_methods
                }
                print(f"[GELATO QUOTE] /shipment-methods: {len(method_uids)} method(s) for {country_code} — pricing via draft orders")
            else:
                method_uids = None
                days_by_uid = {}
        else:
            print(f"[GELATO QUOTE] /shipment-methods returned {resp.status_code} for {country_code}")
            method_uids = None
            days_by_uid = {}
    except Exception as e:
        print(f"[GELATO QUOTE] /shipment-methods error for {country_code}: {e}")
        method_uids = None
        days_by_uid = {}

    # ── Step 2: Fall back to draft orders for pricing ───────────────────────
    if method_uids is None:
        method_uids = ["express", "normal"]

    result = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        futures = {
            pool.submit(_get_draft_price, country_code, uid, currency, postal_code): uid
            for uid in method_uids
        }
        try:
            for future in concurrent.futures.as_completed(futures, timeout=40):
                uid = futures[future]
                try:
                    cost = future.result()
                    if cost and cost > 0:
                        min_d, max_d = days_by_uid.get(uid, ("", ""))
                        result[uid] = _build_option(uid, cost, min_d, max_d)
                except Exception as e:
                    print(f"[GELATO QUOTE] Draft future error for {uid}: {e}")
        except concurrent.futures.TimeoutError:
            print(f"[GELATO QUOTE] Draft-order futures timed out after 40s — returning partial results ({len(result)} options)")
            for future, uid in futures.items():
                if not future.done():
                    future.cancel()

    if result:
        print(f"[GELATO QUOTE] Draft-order pricing for {country_code} (postal: {postal_code or 'default'}): {list(result.keys())}")
    else:
        print(f"[GELATO QUOTE] Could not get pricing for {country_code}")

    return result


def _build_option(uid: str, cost: float, min_days=None, max_days=None) -> dict:
    """Build a shipping option dict for the checkout frontend."""
    names = _METHOD_NAMES.get(uid, {"es": f"{uid} — Gelato", "en": f"{uid} — Gelato"})
    if min_days and max_days:
        days_es = f"{min_days}-{max_days} días hábiles"
        days_en = f"{min_days}-{max_days} business days"
    else:
        default_days = _METHOD_DAYS.get(uid, {"es": "7-21 días hábiles", "en": "7-21 business days"})
        days_es = default_days["es"]
        days_en = default_days["en"]
    return {
        "name_es": names["es"],
        "name_en": names["en"],
        "days_es": days_es,
        "days_en": days_en,
        "gelato_cost": round(float(cost), 2),
    }
