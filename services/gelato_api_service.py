def _get_api_key() -> str:
    key = os.environ.get("GELATO_API_KEY", "")
    if not key:
        raise RuntimeError("GELATO_API_KEY environment variable is not set")
    return key


def _headers() -> dict:
    return {
        "X-API-KEY": _get_api_key(),
        "Content-Type": "application/json",
    }


def _app_base_url() -> str:
    url = os.environ.get("APP_BASE_URL", "").rstrip("/")
    if not url:
        domain = os.environ.get("REPLIT_DEV_DOMAIN", "")
        if domain:
            url = f"https://{domain}"
    return url


def build_pdf_url(session_id: str, filename: str = "combined_34p.pdf") -> str:
    """
    Build a publicly accessible HTTPS URL for a Gelato PDF file.
    Uses the Flask /preview-pdf/gelato/<session_id>/<filename> route.

    Default is the combined 34-page PDF (cover wrap + interior + end papers).
    """
    base = _app_base_url()
    if not base:
        raise RuntimeError(
            "Cannot build PDF URL: APP_BASE_URL or REPLIT_DEV_DOMAIN not set"
        )
    return f"{base}/preview-pdf/gelato/{session_id}/{filename}"


def build_cover_url(session_id: str, filename: str = "cover_wrap.pdf") -> str:
    """Build a publicly accessible HTTPS URL for the cover wrap PDF (kept for reference)."""
    base = _app_base_url()
    if not base:
        raise RuntimeError(
            "Cannot build cover URL: APP_BASE_URL or REPLIT_DEV_DOMAIN not set"
        )
    return f"{base}/preview-pdf/gelato/{session_id}/{filename}"


def create_order(
    order_reference_id: str,
    customer_name: str,
    customer_email: str,
    shipping_address: dict,
    combined_pdf_url: str,
    interior_pdf_url: str = None,  # kept for backwards compat, ignored
    cover_pdf_url: str = None,     # kept for backwards compat, ignored
    quantity: int = 1,
    sku: str = HC_A4_SKU,
    currency: str = "USD",
    dry_run: bool = None,
    shipment_method_uid: str = "express",
) -> Optional[dict]:
    """
    Submit a print order to Gelato v3.

    Gelato photobooks require a single combined PDF containing:
      Page 1     : Cover wrap (478×326mm full spread with bleed)
      Page 2     : Blank end paper (inside front cover)
      Pages 3-32 : 30 interior pages
      Pages 33-34: Blank end papers (inside back cover)

    Args:
        order_reference_id: Your internal order ID (e.g. 'ORD-12345')
        customer_name:      Full name of the recipient
        customer_email:     Customer email for Gelato notifications
        shipping_address:   Dict with keys: address_line1, address_line2,
                            city, state, post_code, country, phone
        combined_pdf_url:   Public HTTPS URL to the combined 34-page PDF
                            (generated by gelato_combined_pdf_service)
        quantity:           Number of copies (default 1)
        sku:                Gelato product SKU (default HC A4 210×280mm)
        currency:           ISO currency code (default USD)
        dry_run:            If True, creates a draft order (not printed).
                            Defaults to GELATO_USE_SANDBOX env var.

    Returns:
        Gelato order response dict, or None on failure.
    """
    if dry_run is None:
        dry_run = os.environ.get("GELATO_USE_SANDBOX", "true").lower() == "true"

    url = f"{GELATO_API_BASE}/v3/orders"

    payload = {
        "orderType": "order",
        "orderReferenceId": order_reference_id,
        "customerReferenceId": order_reference_id,
        "currency": currency,
        "items": [
            {
                "itemReferenceId": f"{order_reference_id}-1",
                "productUid": sku,
                "quantity": quantity,
                "pageCount": 30,       # interior page count (Gelato adds 4 for covers = 34 total)
                "fileUrl": combined_pdf_url,   # single combined PDF (34 pages)
            }
        ],
        "shipmentMethodUid": shipment_method_uid,
        "shippingAddress": {
            "firstName": customer_name.split()[0] if customer_name else "",
            "lastName":  " ".join(customer_name.split()[1:]) if customer_name else "",
            "addressLine1": shipping_address.get("address_line1", ""),
            "addressLine2": shipping_address.get("address_line2", ""),
            "city":        shipping_address.get("city", ""),
            "state":       shipping_address.get("state", ""),
            "postCode":    shipping_address.get("post_code") or shipping_address.get("postal_code", ""),
            "country":     shipping_address.get("country", "US"),
            "email":       customer_email,
            "phone":       shipping_address.get("phone", ""),
        },
        "metadata": [],
    }

    if dry_run:
        payload["orderType"] = "draft"
        print(f"[GELATO API] DRY RUN — order will be created as draft (not printed)")

    print(f"[GELATO API] Creating order: {order_reference_id}")
    print(f"[GELATO API] Combined PDF (34 pages): {combined_pdf_url}")

    try:
        response = requests.post(url, headers=_headers(), json=payload, timeout=60)
        if response.status_code in (200, 201):
            data = response.json()
            print(f"[GELATO API] Order created: {data.get('id')}, status: {data.get('status')}")
            return data
        else:
            print(f"[GELATO API] Order creation failed: {response.status_code}")
            print(f"[GELATO API] Response: {response.text[:1000]}")
            return None
    except Exception as e:
        print(f"[GELATO API] Error creating order: {e}")
        return None


def get_order_status(gelato_order_id: str) -> Optional[dict]:
    """
    Retrieve the current status of a Gelato order.

    Returns dict with keys:
      status, status_text (es/en), tracking_code, tracking_url, carrier
    """
    url = f"{GELATO_API_BASE}/v3/orders/{gelato_order_id}"

    try:
        response = requests.get(url, headers=_headers(), timeout=30)
        if response.status_code == 200:
            data = response.json()
            status = data.get("fulfillmentStatus") or data.get("status", "unknown")
            shipments = data.get("shipments", [])
            tracking_code = None
            tracking_url = None
            carrier = None
            if shipments:
                s = shipments[0]
                tracking_code = s.get("trackingCode")
                tracking_url = s.get("trackingUrl")
                carrier = s.get("carrier")

            result = {
                "status": status,
                "status_text": STATUS_TRANSLATIONS.get(status, {"es": status, "en": status}),
                "tracking_code": tracking_code,
                "tracking_url": tracking_url,
                "carrier": carrier,
                "raw": data,
            }
            print(f"[GELATO API] Order {gelato_order_id} status: {status}")
            return result
        else:
            print(f"[GELATO API] Status check failed: {response.status_code} — {response.text[:300]}")
            return None
    except Exception as e:
        print(f"[GELATO API] Error getting order status: {e}")
        return None


def cancel_order(gelato_order_id: str) -> bool:
    """
    Cancel a Gelato order. Only works while status is 'created' or 'draft'.
    Returns True if successfully cancelled.
    """
    url = f"{GELATO_API_BASE}/v3/orders/{gelato_order_id}"

    try:
        response = requests.delete(url, headers=_headers(), timeout=30)
        if response.status_code in (200, 204):
            print(f"[GELATO API] Order {gelato_order_id} cancelled")
            return True
        else:
            print(f"[GELATO API] Cancel failed: {response.status_code} — {response.text[:300]}")
            return False
    except Exception as e:
        print(f"[GELATO API] Error cancelling order: {e}")
        return False


def verify_webhook_signature(payload_bytes: bytes, signature_header: str) -> bool:
    """
    Verify a Gelato webhook signature.
    Gelato signs with HMAC-SHA256 using the webhook secret.
    Returns True if the signature matches.
    """
    secret = os.environ.get("GELATO_WEBHOOK_SECRET", "")
    if not secret:
        print("[GELATO WEBHOOK] No GELATO_WEBHOOK_SECRET set — skipping verification")
        return True

    expected = hmac.new(
        secret.encode("utf-8"),
        payload_bytes,
        hashlib.sha256,
    ).hexdigest()

    received = signature_header.split("=")[-1] if "=" in signature_header else signature_header
    return hmac.compare_digest(expected, received)


